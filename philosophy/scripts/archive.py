"""Build formatted, navigable archive pages from the frozen source."""

import argparse
from pathlib import Path

import corpus
import daily
from models import Passage


def render_archive(source: bytes, passages: list[Passage]) -> dict[str, bytes]:
    """Render one passage per page with previous and next reading links."""
    pages: dict[str, bytes] = {}
    for reading_number, passage in enumerate(passages, start=1):
        filename = Path(daily.reading_url(reading_number)).name
        pages[filename] = (
            f"# Reading {reading_number}\n\n"
            "[Today's reading](../../README.md) · "
            "[All readings](../README.md#readings)\n\n"
            "<!-- Generated by scripts/archive.py; do not edit. -->"
        ).encode("utf-8")
        previous_url = daily.previous_reading_url(reading_number)
        next_url = (
            daily.reading_url(reading_number + 1)
            if reading_number < len(passages)
            else None
        )
        prefix = "philosophy/readings/"
        pages[filename] += daily.render_reading(
            source,
            passage,
            None,
            reading_number,
            len(passages),
            previous_url=previous_url.removeprefix(prefix)
            if previous_url
            else None,
            next_url=next_url.removeprefix(prefix) if next_url else None,
            archive_url="../README.md#readings",
        )
    return pages


def prepare_archive(
    root: Path = corpus.REPOSITORY_ROOT, check_only: bool = False
) -> None:
    """Generate archive pages, or verify their exact source and navigation."""
    source, passages, _ = corpus.load_corpus(root)
    pages = render_archive(source, passages)
    directory = root / "philosophy/readings"
    if not check_only:
        directory.mkdir(parents=True, exist_ok=True)
    obsolete_pages = list(directory.glob("book-[0-9][0-9].md"))
    if check_only and obsolete_pages:
        raise ValueError("Obsolete book pages remain; rebuild the archive")
    for filename, content in pages.items():
        path = directory / filename
        if check_only:
            if not path.exists() or path.read_bytes() != content:
                raise ValueError(f"Archive is out of date: {path}")
        else:
            path.write_bytes(content)
    if not check_only:
        for path in obsolete_pages:
            path.unlink()


def main() -> None:
    """Run the offline archive generation or verification command."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    try:
        prepare_archive(check_only=arguments.check)
    except (ValueError, OSError) as error:
        parser.exit(1, f"Archive stopped: {error}\n")
    print("Formatted reading archive verified.")


if __name__ == "__main__":
    main()
